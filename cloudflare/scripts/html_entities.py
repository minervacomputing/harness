"""Writes src/lib/html-entities.ts: the tables Python's `html.unescape` uses (the WHATWG named character
references and the numeric references it replaces or drops), so text.ts decodes exactly as the backend does.

Run from cloudflare/: cd ../backend && uv run python -I ../cloudflare/scripts/html_entities.py
"""

import html
import html.entities
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "lib" / "html-entities.ts"


def literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=True)


def main() -> None:
    names = html.entities.html5
    invalid_refs = html._invalid_charrefs  # noqa: SLF001
    invalid_points = sorted(html._invalid_codepoints)  # noqa: SLF001
    lines = [
        "// Generated by scripts/html_entities.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}'s html module. Do not edit.",
        "",
        "/** Named character references, with and without `;` where HTML allows both. */",
        "export const NAMED: Readonly<Record<string, string>> = {",
    ]
    lines += [f"\t{literal(name)}: {literal(value)}," for name, value in sorted(names.items())]
    lines += [
        "};",
        "",
        "/** Numeric references HTML replaces, such as the Windows-1252 range. */",
        "export const REPLACED: ReadonlyMap<number, string> = new Map([",
    ]
    lines += [f"\t[0x{point:x}, {literal(value)}]," for point, value in sorted(invalid_refs.items())]
    lines += [
        "]);",
        "",
        "/** Numeric references HTML drops. */",
        "export const DROPPED: ReadonlySet<number> = new Set([",
    ]
    lines += ["\t" + ", ".join(f"0x{point:x}" for point in invalid_points[i : i + 10]) + "," for i in range(0, len(invalid_points), 10)]
    lines += ["]);", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(names)} names, {len(invalid_refs)} replaced, {len(invalid_points)} dropped")


if __name__ == "__main__":
    main()
