// The registered connectors. Declarations are validated before anything can use them, and every
// operation's fingerprint is computed once, when the registry is built, so the lookups a run start makes
// stay synchronous.

import { z } from "zod";
import type { $ZodLazy, $ZodType, $ZodTypes } from "zod/v4/core";
import type { Json, JsonObject } from "../lib/json.ts";
import { sha256Hex } from "../lib/hash.ts";
import { hashInput } from "../lib/canonical.ts";
import { isRecord } from "../lib/schema.ts";
import { ACCOUNT_KIND, type Connector, type Operation, actionOf, kindOf, nests, operationOf, requiresOf, termsOf } from "./connector.ts";
import { compareLists } from "./policy.ts";

/** No digits: a second connection of a provider gets a numeric suffix (todoist2), which then cannot collide. */
export const NAME_PATTERN = /^[a-z]+(_[a-z]+)*$/;
export const MAX_TOOL_NAME = 64;
export const MAX_ALIAS_SUFFIX = "99";
/** Set by the flow itself; a connector's `authorizeParams` must not replace them. */
export const RESERVED_AUTHORIZE_PARAMS: ReadonlySet<string> = new Set([
	"client_id",
	"client_secret",
	"code",
	"code_challenge",
	"code_challenge_method",
	"grant_type",
	"login_hint",
	"redirect_uri",
	"resource",
	"response_type",
	"scope",
	"state",
]);

export class InvalidConnector extends Error {
	constructor(message: string) {
		super(message);
		this.name = "InvalidConnector";
	}
}

/** No such connector or operation. */
export class LookupError extends Error {
	constructor(message: string) {
		super(message);
		this.name = "LookupError";
	}
}

function chainOf(connector: Connector, action: string): string[] {
	const chain: string[] = [];
	const requires = requiresOf(connector);
	let current: string | null = action;
	while (current !== null) {
		if (chain.includes(current)) throw new InvalidConnector(`${connector.slug}: the action ${JSON.stringify(action)} requires itself.`);
		chain.push(current);
		current = requires(current);
	}
	return chain;
}

/**
 * The input's JSON Schema, as the model sees it and as the fingerprint covers it: zod's, of the input
 * (fields with defaults are optional), without `$schema`. Generated by the pinned zod, so it is the same in
 * every deploy of a version.
 */
export function inputSchema(op: Operation<never>): JsonObject {
	const schema = { ...(z.toJSONSchema(op.input as z.ZodType, { io: "input" }) as JsonObject) };
	delete schema.$schema;
	return schema;
}

const UNKNOWN_FIELDS = "inputs are strict objects, which refuse unknown fields";

/** The root, through the input side of pipes (a `.transform()` after the whole input), is an object. */
function rootIsObject(schema: $ZodType): boolean {
	const def = (schema as $ZodTypes)._zod.def;
	return def.type === "object" || (def.type === "pipe" && rootIsObject(def.in));
}

/**
 * Throws unless the input is strict at every depth: every object a strict object (unknown fields refused),
 * every record lib/schema.ts's `record`, no coercion, nothing that transforms before it validates and
 * nothing that swallows a failure (`catch`). `any` and `unknown` take any JSON value as it is. Nothing may
 * assign an input's keys to an object, where "__proto__" would set its prototype, or read one that may be
 * inherited: not zod's own record, a catchall, an intersection's merge or a field named as a property of
 * Object.prototype. Read from zod's own tree, so it is checked on what parses, not on what the JSON Schema
 * shows.
 */
function checkStrict(where: string, input: $ZodType): void {
	const refuse = (rule: string, at: string): never => {
		throw new InvalidConnector(`${where}: ${rule} (at ${at}).`);
	};
	if (!rootIsObject(input)) refuse(UNKNOWN_FIELDS, "input");
	const seen = new Set<$ZodType>();
	const walk = (schema: $ZodType, at: string): void => {
		if (seen.has(schema)) return;
		seen.add(schema);
		const node = schema as $ZodTypes;
		const def = node._zod.def;
		if ("coerce" in def && def.coerce) refuse("inputs never coerce", at);
		switch (def.type) {
			case "object":
				// A catchall (or none, which strips) assigns what the shape does not name.
				if (def.catchall?._zod.def.type !== "never") refuse(UNKNOWN_FIELDS, at);
				for (const [name, field] of Object.entries(def.shape)) {
					// zod reads a field from the input with `input[name]`, so a missing "constructor" is
					// Object.prototype's, and assigns it to the result, where "__proto__" sets the prototype.
					if (Object.hasOwn(Object.prototype, name)) {
						refuse("an input field cannot be named as a property of Object.prototype, which zod would read or assign", `${at}.${name}`);
					}
					walk(field, `${at}.${name}`);
				}
				return;
			case "record":
				if (!isRecord(schema)) refuse('input records are lib/schema.ts\'s record, since zod\'s drops a "__proto__" key', at);
				walk(def.valueType, `${at}{value}`);
				return;
			case "array":
				walk(def.element, `${at}[]`);
				return;
			case "tuple":
				def.items.forEach((item, index) => walk(item, `${at}[${index}]`));
				if (def.rest !== null) walk(def.rest, `${at}[]`);
				return;
			case "union":
				for (const option of def.options) walk(option, at);
				return;
			case "optional":
			case "nullable":
			case "default":
			case "prefault":
			case "nonoptional":
			case "readonly":
				walk(def.innerType, at);
				return;
			case "lazy":
				// The schema zod caches and parses with, not a second call of the getter.
				walk((node as $ZodLazy)._zod.innerType, at);
				return;
			case "pipe":
				// What `in` returns is already strict; a transform after it runs on validated output.
				walk(def.in, at);
				if (def.out._zod.def.type !== "transform") walk(def.out, at);
				return;
			case "transform":
				return refuse("inputs validate before they transform", at);
			case "intersection":
				// zod merges the two results by assigning their shared keys.
				return refuse("inputs cannot use zod's intersection, which assigns the keys it merges", at);
			case "string":
			case "number":
			case "boolean":
			case "null":
			case "literal":
			case "enum":
			case "any":
			case "unknown":
			case "never":
				return;
			default:
				return refuse(`inputs cannot use zod's ${def.type}`, at);
		}
	};
	walk(input, "input");
}

function validateOperation(connector: Connector, op: Operation<never>): void {
	const where = `${connector.slug}.${op.name}`;
	const terms = termsOf(op);
	if (!NAME_PATTERN.test(op.name)) throw new InvalidConnector(`${where}: operation names are lowercase words joined by underscores.`);
	if (`${connector.slug}${MAX_ALIAS_SUFFIX}_${op.name}`.length > MAX_TOOL_NAME) {
		throw new InvalidConnector(`${where}: the tool name would exceed ${MAX_TOOL_NAME} characters.`);
	}
	if (op.needs.length === 0) throw new InvalidConnector(`${where}: declares no needs.`);
	for (const [kindId, action] of op.needs) {
		const kind = kindOf(connector, kindId);
		if (kind === null) throw new InvalidConnector(`${where}: unknown kind ${JSON.stringify(kindId)}.`);
		for (const item of chainOf(connector, action)) {
			if (!kind.actions.includes(item)) throw new InvalidConnector(`${where}: ${JSON.stringify(item)} does not apply to ${JSON.stringify(kindId)}.`);
		}
	}
	// Records may be scoped to any kind the operation needs; the output action must apply to one of them,
	// and records of a kind it does not apply to are dropped.
	const outputChain = chainOf(connector, terms.outputAction);
	if (!op.needs.some(([kindId]) => outputChain.every((item) => kindOf(connector, kindId)?.actions.includes(item)))) {
		throw new InvalidConnector(`${where}: ${JSON.stringify(terms.outputAction)} applies to none of its kinds.`);
	}
	if (terms.consent !== null && connector.auth.type !== "oauth2") throw new InvalidConnector(`${where}: consent needs an OAuth connector.`);
	checkStrict(where, op.input as $ZodType);
	let schema: JsonObject;
	try {
		schema = inputSchema(op);
	} catch {
		throw new InvalidConnector(`${where}: the input has no JSON Schema.`);
	}
	const properties = schema.properties;
	const fields = typeof properties === "object" && properties !== null && !Array.isArray(properties) ? properties : {};
	if (terms.paginated && !Object.hasOwn(fields, "cursor")) throw new InvalidConnector(`${where}: paginated operations take a cursor.`);
}

function validateAuth(connector: Connector): void {
	const oauth = connector.auth;
	if (oauth.type !== "oauth2") return;
	if (!NAME_PATTERN.test(oauth.app)) throw new InvalidConnector(`${connector.slug}: OAuth app names are lowercase words joined by underscores.`);
	const urls = [oauth.authorizeUrl, oauth.tokenUrl, oauth.registrationUrl ?? null];
	if (urls.some((url) => url !== null && !url.startsWith("https://"))) throw new InvalidConnector(`${connector.slug}: OAuth endpoints must use HTTPS.`);
	const names = (oauth.authorizeParams ?? []).map(([name]) => name);
	if (new Set(names).size !== names.length || names.some((name) => RESERVED_AUTHORIZE_PARAMS.has(name))) {
		throw new InvalidConnector(`${connector.slug}: authorize_params repeats or replaces a protocol parameter.`);
	}
}

/** Throws InvalidConnector for the first declaration that breaks a rule. */
export function validate(connectors: readonly Connector[]): void {
	const tools = new Map<string, string>();
	const slugs = new Set<string>();
	for (const connector of connectors) {
		if (!NAME_PATTERN.test(connector.slug) || slugs.has(connector.slug)) {
			throw new InvalidConnector(`${JSON.stringify(connector.slug)}: slugs are unique lowercase words joined by underscores.`);
		}
		slugs.add(connector.slug);
		validateAuth(connector);
		for (const action of connector.actions) {
			if (action.requires !== null && action.requires !== undefined && actionOf(connector, action.requires) === null) {
				throw new InvalidConnector(`${connector.slug}: ${JSON.stringify(action.id)} requires an unknown action.`);
			}
			chainOf(connector, action.id);
		}
		const kindIds = connector.kinds.map((kind) => kind.id);
		if (kindIds.length === 0 || new Set(kindIds).size !== kindIds.length) throw new InvalidConnector(`${connector.slug}: kinds must be declared once each.`);
		if ((connector.browsable ?? []).some((kindId) => !nests(connector, kindId))) {
			throw new InvalidConnector(`${connector.slug}: only hierarchical kinds can be browsed.`);
		}
		const tenancy = connector.tenancy;
		if (tenancy.kind !== "unknown" && !tenancy.label) throw new InvalidConnector(`${connector.slug}: a tenancy names its tenant.`);
		// The account of a connector with a tenant per resource is in no one tenant, so it could not be checked.
		if (tenancy.kind === "resource" && kindIds.includes(ACCOUNT_KIND)) throw new InvalidConnector(`${connector.slug}: a tenant per resource leaves no account kind.`);
		for (const kind of connector.kinds) {
			if (kind.id === ACCOUNT_KIND && (kind.wildcard || kind.hierarchical)) throw new InvalidConnector(`${connector.slug}: the account kind has one resource.`);
			for (const actionId of kind.actions) {
				if (actionOf(connector, actionId) === null) throw new InvalidConnector(`${connector.slug}: ${JSON.stringify(kind.id)} lists an unknown action.`);
			}
		}
		const names = connector.operations.map((op) => op.name);
		if (new Set(names).size !== names.length) throw new InvalidConnector(`${connector.slug}: operation names must be unique.`);
		for (const op of connector.operations) {
			validateOperation(connector, op);
			const tool = `${connector.slug}_${op.name}`;
			const owner = tools.get(tool);
			if (owner !== undefined) throw new InvalidConnector(`${JSON.stringify(tool)} is declared by both ${owner} and ${connector.slug}.`);
			tools.set(tool, connector.slug);
		}
	}
}

/** What the fingerprint covers: everything that decides what a tool means, and not its description. */
export function meaning(connector: Connector, op: Operation<never>): JsonObject {
	const terms = termsOf(op);
	const actions = [...new Set([...op.needs.map(([, action]) => action), terms.outputAction])].sort();
	const kinds = new Set(op.needs.map(([kind]) => kind));
	// Object.fromEntries defines own properties, so an id such as "__proto__" stays a key.
	const requires: JsonObject = Object.fromEntries(actions.map((action) => [action, chainOf(connector, action)]));
	const declared: JsonObject = Object.fromEntries(
		connector.kinds
			.filter((kind) => kinds.has(kind.id))
			.map((kind) => [kind.id, { actions: [...kind.actions].sort(), wildcard: kind.wildcard ?? false, hierarchical: kind.hierarchical ?? false }]),
	);
	const consent: Json =
		terms.consent === null ? null : terms.consent.map((option) => [...new Set(option)].sort()).sort(compareLists);
	return {
		revision: terms.revision,
		input: inputSchema(op),
		needs: [...op.needs].sort(compareLists).map(([kind, action]) => [kind, action]),
		output: terms.outputAction,
		consent,
		mutates: terms.mutates,
		paginated: terms.paginated,
		requires,
		kinds: declared,
		// How a connection policy reads the operation's resources (gateway/tenancy.ts): a run snapshots its limits by it.
		tenancy: connector.tenancy.kind,
	};
}

/**
 * Identifies what a tool means: 16 hex of SHA-256 over `minerva:operation:` and the canonical JSON
 * (lib/canonical.ts) of `meaning`, consent included. Runs snapshot it, and a tool whose meaning changed stops
 * working (OPERATION_CHANGED).
 */
export async function fingerprint(connector: Connector, op: Operation<never>): Promise<string> {
	return (await sha256Hex(hashInput("operation", meaning(connector, op)))).slice(0, 16);
}

/** What a registered connector cannot change: what it declares, and the slug it is found by. */
const DECLARED = ["slug", "kinds", "actions", "auth", "tenancy", "operations", "browsable"] as const;

/** Freezes an object, its own getters first replaced by what they return now, as `Object.freeze` keeps them. */
function freezeValues(value: object): void {
	for (const [key, own] of Object.entries(Object.getOwnPropertyDescriptors(value))) {
		if (!("value" in own)) Object.defineProperty(value, key, { value: Reflect.get(value, key), enumerable: own.enumerable });
	}
	Object.freeze(value);
}

/**
 * Fixes what a connector declares: each declared property becomes an own read-only value, read once (a
 * getter too), and its kinds, actions, auth, tenancy, browsable kinds and operations, with their needs and consent,
 * are frozen all the way down. Not the rest of the connector, which may keep state, nor an operation's zod
 * schema.
 */
function freezeDeclaration(connector: Connector): void {
	for (const key of DECLARED) {
		const own = Object.getOwnPropertyDescriptor(connector, key);
		if (own !== undefined && "value" in own && !own.writable && !own.configurable) continue;
		Object.defineProperty(connector, key, { value: connector[key], enumerable: own?.enumerable ?? true, writable: false, configurable: false });
	}
	const seen = new WeakSet<object>();
	const deep = (value: unknown): void => {
		if (typeof value !== "object" || value === null || seen.has(value)) return;
		seen.add(value);
		freezeValues(value);
		for (const item of Object.values(value)) deep(item);
	};
	for (const part of [connector.kinds, connector.actions, connector.auth, connector.tenancy, connector.browsable]) deep(part);
	for (const op of connector.operations) {
		deep(op.needs);
		deep(op.consent);
		freezeValues(op);
	}
	Object.freeze(connector.operations);
}

/** Validated connectors and their operations' fingerprints. */
export class Registry {
	readonly #connectors: ReadonlyMap<string, Connector>;
	readonly #contracts: ReadonlyMap<string, ReadonlyMap<string, string>>;

	private constructor(connectors: ReadonlyMap<string, Connector>, contracts: ReadonlyMap<string, ReadonlyMap<string, string>>) {
		this.#connectors = connectors;
		this.#contracts = contracts;
	}

	/**
	 * Freezes the declarations, validates them, then
	 * fingerprints every operation, so a contract always describes the declaration it resolves to.
	 */
	static async create(connectors: readonly Connector[]): Promise<Registry> {
		// Fingerprints assume declarations, zod schemas included, are not mutated after registration.
		for (const connector of connectors) freezeDeclaration(connector);
		validate(connectors);
		const contracts = new Map<string, Map<string, string>>();
		for (const connector of connectors) {
			const own = new Map<string, string>();
			for (const op of connector.operations) own.set(op.name, await fingerprint(connector, op));
			contracts.set(connector.slug, own);
		}
		return new Registry(new Map(connectors.map((connector) => [connector.slug, connector])), contracts);
	}

	/** The connector, or null when none has this slug (a connection of a provider no longer declared). */
	find(slug: string): Connector | null {
		return this.#connectors.get(slug) ?? null;
	}

	get(slug: string): Connector {
		const connector = this.find(slug);
		if (connector === null) throw new LookupError(`Unknown connector ${JSON.stringify(slug)}.`);
		return connector;
	}

	all(): Connector[] {
		return [...this.#connectors.values()];
	}

	contract(provider: string, operation: string): string {
		this.get(provider);
		const contract = this.#contracts.get(provider)?.get(operation);
		if (contract === undefined) throw new LookupError(`Unknown operation ${provider}.${operation}.`);
		return contract;
	}

	/** The operation a run's tool refers to, or null when it no longer exists or changed meaning. */
	resolve(provider: string, operation: string, snapshot: string): Operation<never> | null {
		const connector = this.find(provider);
		if (connector === null) return null;
		const op = operationOf(connector, operation);
		if (op === null || this.contract(provider, operation) !== snapshot) return null;
		return op;
	}
}
